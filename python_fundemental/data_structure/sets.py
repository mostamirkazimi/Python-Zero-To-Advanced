# تعریف مجموعه
fruits = {"apple", "banana", "orange"}

# اضافه کردن عنصر
fruits.add("grape")
print("مجموعه:", fruits)

# بررسی وجود عنصر
print("آیا apple وجود دارد؟", "apple" in fruits)

# عملیات مجموعه
set1 = {1, 2, 3}
set2 = {3, 4, 5}

print("اشتراک:", set1 & set2)
print("اجتماع:", set1 | set2)
print("تفاضل:", set1 - set2)
